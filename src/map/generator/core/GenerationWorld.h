/// A building type, as much of it as generators read.
struct GenerationBuildingType
{
	int typeNum = -1;
	int width = 0, height = 0;
	int maxUnitWorking = 0;
	int assignmentLimit = 0;
	int shootingRange = 0;
	int maxBullets = 0;
	std::array<int, MaterialSlotCount> maxMaterial{};
	bool runtimeAvailable = false;
	bool occupiesGround = true;
	bool isBuildingSite = false;
	std::string type;
	BuildingType *handle = nullptr;
	explicit operator bool() const { return handle != nullptr; }
};

/// A placed building.
struct GenerationBuilding
{
	Building *handle = nullptr;
	int typeNum = -1;
	int posX = 0, posY = 0;
	GenerationBuildingType type;
	explicit operator bool() const { return handle != nullptr; }
};

/// Where a team starts, with Team::StartPosSource's meaning for `source`.
struct GenerationTeamStart
{
	int x = 0, y = 0;
	int source = 0;
	static constexpr int FromSwarm = 3;
};

/// A unit, as much of it as generation validation reads.
struct GenerationUnit
{
	static constexpr int Worker = 0; ///< UnitConsts.h's WORKER
	int typeNum = -1;
	int posX = 0, posY = 0;
};

class GenerationWorld
{
  public:
	// Implicit for the same reason as GenerationMap's constructors.
	GenerationWorld(Game &game);
	GenerationWorld(const Game &game);

	GenerationMap map;

	/// The bound Game, for the generation service and tests only; generators never need it.
	Game &target() const { return *game; }
	/// Lets a caller holding a Game pass a temporary view to a helper taking GenerationWorld &,
	/// as in `scoreStarts(GenerationWorld(game).ref(), teams)`; the view lives to the end of
	/// the full expression.
	GenerationWorld &ref() { return *this; }

	// === Teams and starts ===
	int teamsCount() const;
	void addTeam();
	bool hasTeam(int team) const;
	GenerationTeamStart teamStart(int team) const;
	void setTeamStart(int team, int x, int y);
	void setTeamStart(int team, int x, int y, int source);
	/// Team::createLists, once a colony's starting entities are placed.
	void finishTeam(int team);
	int resourceScarcityLevel() const;

	// === Buildings and units ===
	GenerationBuildingType startingBuildingType() const;
	GenerationBuildingType buildingType(const std::string &name, int level,
										bool isBuildingSite) const;
	GenerationBuildingType buildingType(int typeNum) const;
	bool isBuildingTypeAvailable(int typeNum) const;
	/// The old toolkit's short building number (IntBuildingType) at a level.
	GenerationBuildingType legacyBuildingType(int shortType, int level, bool isBuildingSite) const;
	bool checkRoomForBuilding(int x, int y, const GenerationBuildingType &type, int team) const
	{
		return checkRoomForBuilding(x, y, type.handle, team);
	}
	/// Game::checkRoomForBuilding without the fog-of-war test.
	bool checkRoomForBuilding(int x, int y, const BuildingType *type, int team) const;
	static GenerationBuilding describe(Building *building);
	GenerationBuilding addBuilding(int x, int y, int typeNum, int team, Sint32 unitWorking = 1,
								   Sint32 unitWorkingFuture = 1);
	bool addWorker(int x, int y, int team);
	/// Team::addToStaticAbilitiesLists for a building placed after the team's lists were made.
	void registerBuilding(int team, const GenerationBuilding &building);
	void setBuildingBullets(const GenerationBuilding &building, int bullets);
	void setBuildingMaterial(const GenerationBuilding &building, int material, int amount);
	void updateBuildingCallLists(const GenerationBuilding &building);
	void updateBuilding(const GenerationBuilding &building);
	std::vector<GenerationBuilding> teamBuildings(int team) const;
	std::vector<GenerationUnit> teamUnits(int team) const;
	/// The type number of the building or unit with this global id (Building/Unit GIDs).
	int buildingTypeNumAt(Uint16 gbid) const;
	int unitTypeNumAt(Uint16 guid) const;
	/// The team of a building or unit global id (BuildingUtils/UnitUtils::GIDtoTeam).
	static constexpr int EntitiesPerTeam = 1024;
	static int buildingTeamOf(Uint16 gbid) { return gbid / EntitiesPerTeam; }
	static int unitTeamOf(Uint16 guid) { return guid / EntitiesPerTeam; }

	// === Scratch worlds ===
	/// Binds the map to its game (Map::setGame), as the service does before generating.
	void attachMap();
	/// Seeds the game header and world random streams, as the service does.
	void seedRandom(std::uint32_t seed);

  private:
	Game *game;
};

/// A fresh world a generator owns, for trial placements and previews. Lives on the heap:
/// preview workers have smaller stacks than the main thread.
class GenerationScratchWorld
{
	std::unique_ptr<Game> game;
	std::unique_ptr<GenerationWorld> view;

  public:
	GenerationScratchWorld();
	~GenerationScratchWorld();
	GenerationScratchWorld(const GenerationScratchWorld &) = delete;
	GenerationScratchWorld &operator=(const GenerationScratchWorld &) = delete;
	GenerationWorld &world() { return *view; }
	GenerationWorld *operator->() { return view.get(); }
	GenerationWorld &operator*() { return *view; }
};
