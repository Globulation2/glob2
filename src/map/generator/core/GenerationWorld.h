#pragma once
// The narrow world a map generator writes into. Generators, their shared helpers and their
// validators reach the Map and Game through these two views instead of including Map.h or
// Game.h, so editing simulation headers no longer rebuilds every generator.
//
// GenerationMap mirrors the subset of Map's interface generators use, under the same names, so
// generator code reads as before. Per-cell reads are inline over the plain cell arrays Map keeps
// in its live MapState::View (the same records Map's own inline accessors read), so no hot read
// in a generation loop becomes a call. Writes and the few non-trivial queries forward, out of
// line, to the Map member of the same name in GenerationService.cpp. Those Map members were
// already out of line, or (setFertility, setResourcesGrow, setGroundUnit) are not called per
// cell in a loop; the one whole-map fertility stamp is a single coarse call (storeFertility).
// Generation runs the same code as before, so the generated bytes do not change.
//
// GenerationWorld is the Game side: teams and their starts, starting buildings and workers as
// small descriptors, and scratch worlds for trial placements. Random draws do not come from
// here: a generator draws from its named GenerationContext streams.
#include "CellRules.h"
#include "MapState.h"
#include "MapStateView.h"
#include "Ressource.h"
#include "TeamCapacity.h"
#include "TerrainPropertiesLayout.h"
#include "TerrainType.h"
#include <array>
#include <cstddef>
#include <cstdint>
#include <memory>
#include <span>
#include <string>
#include <utility>
#include <vector>

#ifndef NOGUID
#define NOGUID 0xFFFF
#endif

class Map;
class Game;
class Building;
struct BuildingType;

class GenerationMap
{
  public:
	// Implicit, so a caller holding a real Map (the service, tools, tests) can pass it where a
	// helper takes a const view; a view is three pointers.
	GenerationMap(Map &map);
	GenerationMap(const Map &map);

	/// The bound Map, for the generation service and tests only; generators never need it.
	Map &target() const { return *map; }
	/// Lets a caller holding a Map pass a temporary view to a helper taking GenerationMap &;
	/// the view lives to the end of the full expression.
	GenerationMap &ref() { return *this; }

	// === Size and wrap ===
	int getW() const { return view->width; }
	int getH() const { return view->height; }
	int getMaskW() const { return int(view->wMask); }
	int getMaskH() const { return int(view->hMask); }
	int getShiftW() const { return int(view->wDec); }
	size_t coordToIndex(int x, int y) const
	{
		return ((y & int(view->hMask)) << int(view->wDec)) + (x & int(view->wMask));
	}
	int normalizeX(int x) const { return x & int(view->wMask); }
	int normalizeY(int y) const { return y & int(view->hMask); }
	size_t cellCount() const { return view->resources.size(); }
	Sint32 warpDistSquare(int px, int py, int qx, int qy) const;
	/// Resizes the map; only for scratch worlds a generator builds itself.
	void setSize(int wDec, int hDec);

	// === Terrain ===
	TerrainType vertexTerrainAt(size_t index) const { return (*vertices)[index]; }
	TerrainType vertexTerrainAt(int x, int y) const { return (*vertices)[coordToIndex(x, y)]; }
	std::span<const TerrainType> vertexTerrainState() const { return *vertices; }
	TerrainType terrainTypeAt(size_t index) const
	{
		const auto &corners = (*view->rules)[view->cellRules[index]].corners;
		return corners[0] == corners[3] ? corners[0] : MIXED_TERRAIN;
	}
	TerrainType terrainTypeAt(int x, int y) const { return terrainTypeAt(coordToIndex(x, y)); }
	const TerrainProperties &terrainPropertiesAt(size_t index) const
	{
		return view->terrainProperties(index);
	}
	const TerrainProperties &terrainPropertiesAt(int x, int y) const
	{
		return terrainPropertiesAt(coordToIndex(x, y));
	}
	const TerrainProperties &terrainProperties(TerrainType type) const
	{
		return view->terrainRegistry->properties(type);
	}
	const TerrainRegistry &terrainRegistry() const { return *view->terrainRegistry; }
	bool isWater(int x, int y) const { return terrainTypeAt(x, y) == WATER; }
	bool isWater(unsigned pos) const { return terrainTypeAt(size_t(pos)) == WATER; }
	bool isGrass(int x, int y) const { return terrainTypeAt(x, y) == GRASS; }
	bool isGrass(unsigned pos) const { return terrainTypeAt(size_t(pos)) == GRASS; }
	bool isSand(int x, int y) const { return terrainTypeAt(x, y) == SAND; }
	Uint32 terrainSeed() const;

	void setVertexTerrain(size_t index, TerrainType type);
	void setVertexTerrain(int x, int y, TerrainType type)
	{
		setVertexTerrain(coordToIndex(x, y), type);
	}
	void assignVertexTerrain(std::span<const TerrainType> vertices);
	void fillTerrain(TerrainType type);
	std::vector<size_t> paintVertices(const std::vector<std::pair<int, int>> &vertices,
									  TerrainType type, bool beaches = true);
	void paintVertexSquare(int x, int y, TerrainType type, int l);
	void layBeaches();

	/// Holds Map's terrain edit batch open: derived terrain state is finished once, when the
	/// outermost batch closes (Map::TerrainEditBatch).
	class TerrainEditBatch
	{
		struct Hold;
		std::unique_ptr<Hold> hold;

	  public:
		explicit TerrainEditBatch(Map &map);
		~TerrainEditBatch();
		TerrainEditBatch(const TerrainEditBatch &) = delete;
		TerrainEditBatch &operator=(const TerrainEditBatch &) = delete;
	};
	TerrainEditBatch editTerrain() { return TerrainEditBatch(*map); }

	// === Resources ===
	const ResourceRegistry &resourceRegistry() const { return *view->resourceRegistry; }
	const ResourceProperties &resourceProperties(ResourceId type) const
	{
		return view->resourceRegistry->properties(type);
	}
	const ResourceProperties &resourcePropertiesByIndex(int type) const
	{
		return resourceProperties(static_cast<ResourceId>(type));
	}
	const Resource &getResource(int x, int y) const
	{
		return view->resources[coordToIndex(x, y)].resource;
	}
	const Resource &getResource(size_t pos) const { return view->resources[pos].resource; }
	std::span<const MapState::ResourceCell> resourceState() const { return view->resources; }
	bool isResource(int x, int y) const { return getResource(x, y).type != NO_RES_TYPE; }
	bool isResource(int x, int y, int *resourceType) const
	{
		const Resource &resource = getResource(x, y);
		if (resource.type == NO_RES_TYPE)
			return false;
		*resourceType = resource.type;
		return true;
	}
	bool canResourcesGrow(int x, int y) const
	{
		return view->resources[coordToIndex(x, y)].mayGrow &&
			   terrainPropertiesAt(x, y).resourcesGrow;
	}
	bool terrainSupportsResourceAt(size_t index, ResourceId resource) const
	{
		return MapState::terrainSupportsResource(*view, index, resource);
	}
	bool terrainSupportsResourceAt(int x, int y, ResourceId resource) const
	{
		return terrainSupportsResourceAt(coordToIndex(x, y), resource);
	}
	bool terrainSupportsResourceAtByIndex(int x, int y, int resource) const
	{
		return resource >= 0 && resource < NO_RES_TYPE &&
			   terrainSupportsResourceAt(x, y, static_cast<ResourceId>(resource));
	}
	bool terrainSupportsResourceType(TerrainType terrain, ResourceId resource) const
	{
		return MapState::terrainSupportsResourceType(*view, terrain, resource);
	}
	bool terrainSupportsMaterialAtSlot(int x, int y, int material) const
	{
		return MapState::terrainSupportsMaterial(*view, coordToIndex(x, y), material);
	}
	bool terrainSupportsMaterialAt(int x, int y, MaterialId material) const
	{
		return terrainSupportsMaterialAtSlot(x, y, materialIndex(material));
	}
	/// Map::isResourceAllowed: the terrain is a habitat and nothing the deposit would block
	/// stands on the tile.
	bool isResourceAllowed(int x, int y, int type) const
	{
		if (!terrainSupportsResourceAtByIndex(x, y, type))
			return false;
		const auto &p = resourcePropertiesByIndex(type);
		const auto &cell = view->occupancy[coordToIndex(x, y)];
		return (!p.blocksBuilding || cell.building == NOGBID) &&
			   (!p.blocksGround || cell.groundUnit == NOGUID) &&
			   (!p.blocksAir || cell.airUnit == NOGUID);
	}
	Uint16 materialAmountAtSlot(size_t index, int material) const
	{
		return MapState::materialAmountAt(*view, index, material);
	}
	Uint16 materialAmountAt(size_t index, MaterialId material) const
	{
		return materialAmountAtSlot(index, static_cast<int>(material));
	}
	MaterialMask materialMaskAt(size_t index) const
	{
		return MapState::materialMaskAt(*view, index);
	}
	bool resourceBlocksGround(size_t index) const
	{
		return MapState::resourceBlocksGround(*view, index);
	}
	bool resourceBlocksBuilding(size_t index) const
	{
		return MapState::resourceBlocksBuilding(*view, index);
	}
	std::uint64_t materialRenewalPotentialAtSlot(size_t index, int material) const;
	std::uint64_t materialRenewalPotentialAt(size_t index, MaterialId material) const
	{
		return materialRenewalPotentialAtSlot(index, materialIndex(material));
	}
	std::uint64_t materialExpansionRateAtSlot(size_t index, int material) const;
	std::uint64_t materialExpansionRateAt(size_t index, MaterialId material) const
	{
		return materialExpansionRateAtSlot(index, materialIndex(material));
	}
	/// Map::stateView: the live view plus the game's growth settings and growth field.
	MapState::View stateView() const;
	/// Whether Map's fertility growth cache is current (generation work accounting).
	bool growthCacheValid() const;

	void setResource(int x, int y, ResourceId type, int l);
	void setResourceByIndex(int x, int y, int type, int l)
	{
		if (type >= 0 && type < NO_RES_TYPE)
			setResource(x, y, static_cast<ResourceId>(type), l);
	}
	void setNoResource(int x, int y, int l);
	void replaceResource(size_t index, const Resource &resource,
						 const std::array<Uint16, MaterialCount> *stocks = nullptr);
	void replaceResource(int x, int y, const Resource &resource)
	{
		replaceResource(coordToIndex(x, y), resource);
	}
	void setResourceAmount(size_t index, Uint32 amount);
	void setResourcesGrow(int x, int y, Uint8 value);
	void setFertility(int x, int y, Uint16 value);
	void growResources();
	void smoothResources(int times);
	/// Stamps a fertility field into every tile and records its maximum, as the overlay the
	/// map carries (Map::setFertility over the whole map, then Map::fertilityMaximum). Clamps
	/// each value to what a tile stores.
	void storeFertility(const Fertility::Field &fertility);

	// === Occupancy ===
	Uint16 getBuilding(int x, int y) const { return view->occupancy[coordToIndex(x, y)].building; }
	Uint16 getGroundUnit(int x, int y) const
	{
		return view->occupancy[coordToIndex(x, y)].groundUnit;
	}
	Uint16 getAirUnit(int x, int y) const { return view->occupancy[coordToIndex(x, y)].airUnit; }
	bool isFreeForBuilding(int x, int y) const;
	bool isFreeForBuilding(int x, int y, int w, int h) const;
	bool isHardSpaceForBuilding(int x, int y) const;
	bool isHardSpaceForBuilding(int x, int y, int w, int h) const;
	bool isFreeForGroundUnit(int x, int y, bool canSwim, Uint32 teamMask) const;
	bool isHardSpaceForGroundUnit(int x, int y, bool canSwim, Uint32 me) const;
	void setBuilding(int x, int y, int w, int h, Uint16 gbid);
	void setGroundUnit(int x, int y, Uint16 guid);

  private:
	Map *map;
	// Map keeps this view current whenever its arrays or registries are replaced.
	const MapState::View *view;
	const std::vector<TerrainType> *vertices;
};

