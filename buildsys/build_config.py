"""glob2/BuildConfig.h text, shared by SConstruct and the CMake build.

SConstruct decides each entry from its configure checks; CMake decides the same
entries from its own checks and renders them here (buildsys/cmake_generate.py), so
both build systems write byte-identical headers for the same configuration.
"""
import io


class ConfigurationText:
    """The header text, written in the order entries are added."""
    def __init__(self):
        self.f = io.StringIO()
        self.f.write("#pragma once\n// Generated by SCons.\n")
        self.f.write("\n")

    def add(self, variable, doc, value=""):
        self.f.write("// %s\n" % doc)
        self.f.write("#define %s %s\n" % (variable, value))
        self.f.write("\n")

    def text(self):
        return self.f.getvalue()


def add_package(config, *, datadir, version, font, darwin, windows, china, identity):
    """Entries that need no configure check, up to the client feature switches."""
    config.add("PACKAGE", "Name of package", "\"glob2\"")
    config.add("PACKAGE_BUGREPORT", "Define to the address where bug reports for this package should be sent.", "\"glob2-devel@nongnu.org\"")
    if darwin:
        config.add("PACKAGE_DATA_DIR", "data directory", "\"" + datadir + "../Resources/\"")
    else:
        config.add("PACKAGE_DATA_DIR", "data directory", "\"" + datadir + "\"")
    config.add("PACKAGE_NAME", "Define to the full name of this package.", "\"Globulation 2\"")
    config.add("PACKAGE_TARNAME", "Define to the one symbol short name of this package.", "\"glob2\"")
    config.add("PACKAGE_VERSION", "Define to the version of this package.", "\"" + version + "\"")
    config.add("AUDIO_RECORDER_OSS", "Set the audio input type to OSS; the UNIX Open Sound System")
    if darwin:
        config.add("USE_OSX", "Set when this build is OSX")
    if windows:
        config.add("USE_WIN32", "Set when this build is Win32")
    config.add("PRIMARY_FONT", "This is the primary font Globulation 2 will use", "\"" + font + "\"")
    if china:
        config.add("GLOB2_CHINA_RELEASE", "Mainland China local-play client", "1")
    from client_features import header
    config.f.write(header(identity))


