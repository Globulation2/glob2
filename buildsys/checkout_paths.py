"""Generate glob2/BuildPaths.h: the checkout-specific paths a build embeds.

BuildConfig.h reaches most translation units, so anything in it that differs
between two checkouts of the same commit (an absolute source or build path)
gives every object a different compiler-cache key. The few files that need
those paths include BuildPaths.h instead, and the -D command line carries no
path at all, so a second worktree reuses the first one's cache entries.
"""
from pathlib import Path

from build_layout import write_if_changed

NAMES = ('PACKAGE_SOURCE_DIR', 'PACKAGE_RUNTIME_ASSET_DIR', 'GLOB2_RENDER_SHADER_DIR')


def header(builddir) -> Path:
    return Path(builddir) / 'include/glob2/BuildPaths.h'


def _literal(value: str) -> str:
    return '"' + str(value).replace('\\', '\\\\').replace('"', '\\"') + '"'


def content(**paths) -> str:
    unknown = set(paths) - set(NAMES)
    if unknown:
        raise ValueError('unknown build path: ' + ', '.join(sorted(unknown)))
    lines = ['#pragma once', '// Generated by buildsys/checkout_paths.py. Include only where a path is used.', '']
    for name in NAMES:
        if paths.get(name) is not None:
            lines.append(f'#define {name} {_literal(paths[name])}')
    return '\n'.join(lines) + '\n'


def write(builddir, **paths) -> Path:
    """Write the header (only when its text changed)."""
    path = header(builddir)
    write_if_changed(path, content(**paths))
    return path


def revision(root) -> str:
    """Short HEAD plus a dirty marker for tracked files; 'unknown' outside Git."""
    import subprocess
    try:
        head = subprocess.check_output(['git', 'rev-parse', '--short=12', 'HEAD'], cwd=root,
                                       stderr=subprocess.DEVNULL, text=True).strip()
        dirty = subprocess.check_output(['git', 'status', '--porcelain', '--untracked-files=no'], cwd=root,
                                        stderr=subprocess.DEVNULL, text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        return 'unknown'
    return head + ('-dirty' if dirty else '')


def stamp_content(root) -> str:
    return ('#pragma once\n// Generated by buildsys/checkout_paths.py.\n'
            f'#define GLOB2_BUILD_REVISION {_literal(revision(root))}\n')


def write_stamp(builddir, root) -> Path:
    """Write BuildStamp.h now (the CMake build, on every build)."""
    path = Path(builddir) / 'include/glob2/BuildStamp.h'
    write_if_changed(path, stamp_content(root))
    return path

