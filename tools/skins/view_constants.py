"""Generate native camera constants from the published view sidecars.

Also called by export_views.py after Blender updates the camera sidecars.
Reading the retained JSON needs neither Blender nor NumPy.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SWARMS = ('swarm', 'swarm-crown', 'swarm-clutch', 'swarm-toadstool', 'swarm-coral', 'swarm-skep', 'swarm-bloom')
UNITS = ('worker-walk', 'worker-swim', 'worker-harvest', 'warrior-walk', 'warrior-swim', 'warrior-fight', 'explorer-fly')


def generate():
    lines = ['// Generated by tools/skins/view_constants.py; do not edit.', '#pragma once', '#include <array>',
             'namespace Online {',
             'struct SkinViewTransform { std::array<float,16> inverse, projection; std::array<float,9> normals; };']
    folder = ROOT / 'data/skins/colony-v1'
    for name, clips in [('SkinViews', SWARMS), ('UnitSkinViews', UNITS)]:
        lines.append(f'inline constexpr std::array<SkinViewTransform,{len(clips)}> {name} = {{{{')
        for clip in clips:
            record = json.loads((folder / (clip + '.view.json')).read_text())
            if hashlib.sha256((folder / (clip + '.gsk')).read_bytes()).hexdigest() != record['meshSha256']:
                raise ValueError('View does not match baked mesh: ' + clip)
            if record.get('version') != 1:
                raise ValueError('Unsupported skin view version: ' + clip)
            # C++ aggregate initialization silently zero-fills short arrays.
            # Reject malformed cameras here rather than publishing a bad turn.
            for key, count in (('clipToModel', 16), ('modelToClip', 16), ('normalToModel', 9)):
                values = record.get(key)
                if (not isinstance(values, list) or len(values) != count or
                        any(type(v) not in (int, float) or not math.isfinite(v) for v in values)):
                    raise ValueError('Invalid ' + key + ' camera matrix: ' + clip)
            arrays = ['{{' + ','.join(format(float(v), '.9e') + 'f' for v in record[key]) + '}}'
                      for key in ('clipToModel', 'modelToClip', 'normalToModel')]
            lines.append('    {' + ','.join(arrays) + '}, // ' + clip)
        lines.append('}};')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def write():
    (ROOT / 'src/online/SkinViewTransforms.h').write_text(generate())


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='reject stale native constants')
    args = parser.parse_args()
    if args.check:
        if (ROOT / 'src/online/SkinViewTransforms.h').read_text() != generate():
            parser.exit(1, 'Native skin view constants are stale; run tools/skins/view_constants.py\n')
    else:
        write()
