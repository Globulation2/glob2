"""Collect tournaments, fit and export the deterministic resource refresh model.

run writes a resumable manifest, raw episode labels and exact commands. Diagnostic
CPU is deliberately never reported as gameplay performance. fit splits whole
starting states, balances formats/states/collection games, standardizes on each
training fold, and evaluates the exported integer predictor. emit changes only
the generated header; a new SIM_REVISION and simulation verification are required.
"""
from __future__ import annotations
import argparse
import collections
import concurrent.futures
import csv
import gzip
import hashlib
import json
import math
import os
import shutil
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
FEATURES = ('age', 'q32', 'q128', 'source_added', 'source_removed',
            'source_added_frac_q12', 'source_removed_frac_q12')
HEADS = ('positive_probability', 'negative_probability', 'positive_mean', 'negative_mean')
LIMIT = 1_000_000
LOG = tuple(round(math.log2(1 + i / 256) * 4096) for i in range(257))
SIG = tuple(round(65536 / (1 + math.exp(-x / 1000))) for x in range(-12000, 12001, 50))
HEADER = ROOT / 'src/map/gradient/ResourceGradientModel.h'
DEFAULT_MODEL = ROOT / 'tools/models/resource-gradient.json'


def save(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + '.tmp')
    temp.write_text(json.dumps(value, indent=2) + '\n')
    temp.replace(path)


def sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''): h.update(block)
    return h.hexdigest()


def log_integer(x):
    n = max(0, min(LIMIT, int(x))) + 1
    b = n.bit_length() - 1
    pos = ((n - (1 << b)) << 16) // (1 << b)
    i, f = pos >> 8, pos & 255
    return (b << 12) + LOG[i] + (LOG[i + 1] - LOG[i]) * f // 256


def truncdiv(n, d):
    return n // d if n >= 0 else -((-n) // d)


def predict(model, raw):
    x = [log_integer(v) for v in raw]
    def linear(name):
        head = model[name]
        return max(-10**9, min(10**9, truncdiv(head['bias'] + sum(a*b for a, b in zip(x, head['coef'])), 1 << head['shift'])))
    def sigmoid(z):
        n = max(-12000, min(12000, z)) + 12000
        i = min(n // 50, 479)
        return SIG[i] + (SIG[i + 1] - SIG[i]) * (n - i*50) // 50
    value = truncdiv(sigmoid(linear('positive_probability')) * max(0, linear('positive_mean'))
                     - sigmoid(linear('negative_probability')) * max(0, linear('negative_mean')), 65536)
    return max(-10**9, min(10**9, value))


def validate_model(model):
    if model.get('schema')!=1 or model.get('threshold')!=32000:raise ValueError('Expected the official adaptive-32 model schema')
    if tuple(model['features']) != FEATURES: raise ValueError('Model feature order mismatch')
    bound = log_integer(LIMIT)
    for name in HEADS:
        h = model[name]
        if len(h['coef']) != 7 or h['shift'] not in (28,24,20,16,12,8): raise ValueError('Invalid linear head')
        if not all(type(v) is int for v in [h['bias'], *h['coef']]): raise ValueError('Noninteger coefficients')
        if abs(h['bias']) + sum(abs(c)*bound for c in h['coef']) >= 1 << 61: raise ValueError('Unsafe accumulator')


def emit(model, path):
    validate_model(model)
    text = '''// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by tools/resource_gradient_model.py; do not edit coefficients here.
// Model replacement changes simulation behavior and requires a SIM_REVISION bump.
#pragma once
#include <algorithm>
#include <array>
#include <bit>
#include <cstdint>
#include <cassert>
namespace ResourceGradientModel {
using I=std::int64_t;
struct Sources { std::uint64_t count=0,added=0,removed=0; };
inline I clamp(I x) { return std::clamp(x,I(0),I(1000000)); }
'''
    text += 'inline constexpr I LogLut[]={' + ','.join(map(str, LOG)) + '};\n'
    text += 'inline constexpr I SigLut[]={' + ','.join(map(str, SIG)) + '};\n'
    text += '''// log2(1+x), Q12, and sigmoid, Q16: table interpolation uses integer
// arithmetic only. C++ signed division truncates toward zero throughout.
inline I log(I x) {
    const I n=clamp(x)+1,b=std::bit_width(std::uint64_t(n))-1,base=I(1)<<b;
    const I pos=((n-base)<<16)/base,i=pos>>8,f=pos&255;
    return (b<<12)+LogLut[i]+(LogLut[i+1]-LogLut[i])*f/256;
}
inline I clip(I x) { return std::clamp(x,I(-1000000000),I(1000000000)); }
inline I sigmoid(I z) {
    z=std::clamp(z,I(-12000),I(12000));const I n=z+12000,i=std::min(n/50,I(479)),r=n-i*50;
    return SigLut[i]+(SigLut[i+1]-SigLut[i])*r/50;
}
'''
    for name in HEADS:
        h = model[name]
        text += f'inline I {name}(const std::array<I,7>& x) {{\n'
        text += '    constexpr I c[]={' + ','.join(map(str,h['coef'])) + '};\n'
        text += f'    I z={h["bias"]}LL; for (int i=0;i<7;++i) z+=x[i]*c[i];\n'
        text += f'    return clip(z/(I(1)<<{h["shift"]}));\n}}\n'
    text += '''inline int predict(std::array<I,7> x) {
    for (auto& v:x) v=log(v);
    const I pp=sigmoid(positive_probability(x)),pn=sigmoid(negative_probability(x));
    const I mp=std::max(I(0),positive_mean(x)),mn=std::max(I(0),negative_mean(x));
    return int(clip((pp*mp-pn*mn)/65536));
}
} // namespace ResourceGradientModel
'''
    Path(path).write_text(text)


def default_plan(seeds):
    formats = [('isles-64-duel','isles',64,2,[1,2]),
               ('river-128-4ffa','river',128,4,list(range(1,5))),
               ('river-256-4v4','river',256,8,[1]*4+[2]*4),
               ('savannah-256-16ffa','savannah',256,16,list(range(1,17)))]
    return [dict(format=name,generator=generator,size=size,players=players,alliances=alliances,
                 map_seed=seed*100+i,game_seed=seed*100+i,ai='nicowar')
            for seed in seeds for i,(name,generator,size,players,alliances) in enumerate(formats)]


def run(args):
    binary = Path(args.binary).resolve()
    out = Path(args.output).resolve(); out.mkdir(parents=True,exist_ok=True)
    plan = json.loads(Path(args.plan).read_text()) if args.plan else default_plan(args.seeds)
    identities=[json.dumps(spec,sort_keys=True,separators=(',',':')) for spec in plan]
    if len(set(identities))!=len(identities):raise ValueError('Duplicate starting states in plan')
    binary_hash = sha(binary)
    frozen = dict(schema=1,binary_sha256=binary_hash,model_sha256=sha(DEFAULT_MODEL),header_sha256=sha(HEADER),
                  source_revision=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),
                  tick_cap=args.ticks,threads=args.threads,plan=plan)
    frozen_path = out/'plan.json'
    if frozen_path.exists() and json.loads(frozen_path.read_text()) != frozen:
        raise ValueError('Output has a different frozen plan/build; choose a fresh directory')
    save(frozen_path,frozen)
    manifest_path=out/'manifest.json'
    manifest=json.loads(manifest_path.read_text()) if manifest_path.exists() else []
    done={r['group'] for r in manifest}
    def game(spec):
        identity=json.dumps(spec,sort_keys=True,separators=(',',':'))
        group=hashlib.sha256(identity.encode()).hexdigest()[:16]
        if group in done:return None
        directory=out/group; directory.mkdir(exist_ok=True)
        map_path=directory/'map.map.gz'
        generate=[str(binary),'map','generate',spec['generator'],'--seed',str(spec['map_seed']),
                  '--width',str(spec['size']),'--height',str(spec['size']),'--teams',str(spec['players']),'--output',str(map_path)]
        command=[str(binary),'game','run','--map-file',str(map_path),'--game-seed',str(spec['game_seed']),
                 '--ticks',str(args.ticks),'--compute-threads',str(args.threads),'--gpu','off',
                 '--compute-telemetry','off','--output-dir',str(directory),'--resource-gradient-probe']
        for alliance in spec['alliances']: command+=['--player',spec.get('ai','nicowar'),'--alliance',str(alliance)]
        env={k:v for k,v in os.environ.items() if not k.startswith('GLOB2_RESOURCE_')}
        save(directory/'commands.json',dict(generate=generate,run=command))
        episode=directory/'gradient-episodes.csv'
        result=directory/'result.json'
        # A process can finish before its result is appended to the manifest.
        # Recover that completed game instead of asking the engine to overwrite
        # its result directory. Incomplete attempts are safe to rerun in place.
        recovered=False
        if result.exists() and (episode.exists() or episode.with_suffix('.csv.gz').exists()):
            try:recovered=json.loads(result.read_text()).get('status')=='completed'
            except json.JSONDecodeError:pass
        if not recovered:
            result.unlink(missing_ok=True)
            with (directory/'run.log').open('w') as log:
                subprocess.run(generate,cwd=ROOT,env=env,stdout=log,stderr=subprocess.STDOUT,check=True)
                subprocess.run(command,cwd=ROOT,env=env,stdout=log,stderr=subprocess.STDOUT,check=True)
        result_data=json.loads(result.read_text())
        if result_data.get('status')!='completed':raise RuntimeError(f'Game did not complete: {result}')
        if not episode.exists() and not episode.with_suffix('.csv.gz').exists():
            raise RuntimeError('No episode data: binary lacks the collector')
        # Reference-query CSVs can be large. Compression runs only after the
        # game exits and uses a fixed header so retained evidence is reproducible.
        for name in ['gradient-episodes.csv','gradient-quality.csv']:
            raw=directory/name
            if not raw.exists():continue
            compressed=raw.with_suffix('.csv.gz');temp=compressed.with_suffix('.gz.tmp')
            with raw.open('rb') as inp,temp.open('wb') as file:
                with gzip.GzipFile(filename='',fileobj=file,mode='wb',mtime=0) as gz:
                    shutil.copyfileobj(inp,gz)
            temp.replace(compressed);raw.unlink()
        episode=episode.with_suffix('.csv.gz')
        return dict(group=group,format=spec['format'],episodes=str(episode.relative_to(out)),episode_sha256=sha(episode),
                    binary_sha256=binary_hash,map_sha256=sha(map_path),result_sha256=sha(result),
                    ticks=result_data['ticks'],termination=result_data.get('termination'),spec=spec)
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as pool:
        for future in concurrent.futures.as_completed([pool.submit(game,spec) for spec in plan]):
            record=future.result()
            if record:
                manifest.append(record);save(manifest_path,manifest)
                print(f'{len(manifest)}/{len(plan)} games collected',flush=True)


def dataset(manifests):
    rows=[];seen=set()
    for path in manifests:
        for record in json.loads(Path(path).read_text()):
            p=Path(record['episodes'])
            if not p.is_absolute():p=Path(path).resolve().parent/p
            digest=sha(p)
            if digest != record['episode_sha256']:raise ValueError(f'Dataset hash mismatch: {p}')
            identity=(record['group'],record['binary_sha256'],digest)
            if identity in seen:continue
            seen.add(identity)
            with (gzip.open(p,'rt') if p.suffix=='.gz' else p.open()) as f:
                for line in csv.DictReader(f):
                    if int(line['complete']) != 1:continue
                    row={k:int(v) for k,v in line.items()}
                    row.update(group=record['group'],format=record['format'],collection='|'.join(identity))
                    rows.append(row)
    if not rows:raise ValueError('No complete episodes')
    return rows


def weights(rows):
    import numpy as np
    count=collections.Counter((r['format'],r['group'],r['collection']) for r in rows)
    states=collections.defaultdict(set);collections_by_state=collections.defaultdict(set)
    for fmt,group,collection in count:
        states[fmt].add(group);collections_by_state[fmt,group].add(collection)
    w=np.array([1/(len(states[r['format']])*len(collections_by_state[r['format'],r['group']])*
                   count[r['format'],r['group'],r['collection']]) for r in rows])
    return w*len(w)/w.sum()


def fit_heads(rows):
    import numpy as np
    from sklearn.linear_model import LogisticRegression,Ridge
    x=np.array([[log_integer(r[k]) for k in FEATURES] for r in rows],dtype=np.int64)
    y=np.array([r['defer_extra']-r['refresh_extra'] for r in rows],dtype=float);w=weights(rows)
    mu=np.average(x,axis=0,weights=w);sd=np.sqrt(np.average((x-mu)**2,axis=0,weights=w));sd[sd<1e-12]=1
    z=(x-mu)/sd
    model=dict(schema=1,features=list(FEATURES),threshold=32000)
    def export(beta,intercept):
        for shift in (28,24,20,16,12,8):
            scale=1000*(1<<shift);coef=[round(float(v)*scale) for v in beta];bias=round(float(intercept)*scale)
            bound=abs(bias)+sum(abs(c)*log_integer(LIMIT) for c in coef)
            if bound<1<<61:return dict(coef=coef,bias=bias,shift=shift,accumulator_bound=bound)
        raise ValueError('Unsafe coefficient accumulator')
    for sign,name in [(1,'positive'),(-1,'negative')]:
        mask=sign*y>0
        # Small campaigns may have only one outcome class. Fit the constant
        # head explicitly instead of inventing labels or dropping examples.
        if mask.all() or not mask.any():
            model[name+'_probability']=export(np.zeros(7),12 if mask.all() else -12)
        else:
            est=LogisticRegression(C=1,max_iter=250,random_state=713).fit(z,mask,sample_weight=w)
            beta=est.coef_.ravel()/sd;model[name+'_probability']=export(beta,float(est.intercept_[0])-float(beta@mu))
        if mask.any():
            est=Ridge(alpha=100).fit(z[mask],sign*y[mask],sample_weight=w[mask])
            beta=est.coef_/sd;model[name+'_mean']=export(beta,float(est.intercept_)-float(beta@mu))
        else:model[name+'_mean']=export(np.zeros(7),0)
    validate_model(model)
    return model


def metrics(rows,model):
    import numpy as np
    y=np.array([r['defer_extra']-r['refresh_extra'] for r in rows]);pred=np.array([predict(model,[r[k] for k in FEATURES])/1000 for r in rows]);w=weights(rows)
    take=pred>=32
    return dict(episodes=len(rows),states=len({r['group'] for r in rows}),
                mae=float(np.average(abs(pred-y),weights=w)),mse=float(np.average((pred-y)**2,weights=w)),
                selected_pct=float(np.average(take,weights=w)*100),
                selected_actual_benefit=float(np.average(y[take],weights=w[take])) if take.any() else None)


def fit(args):
    rows=dataset(args.manifest)
    by_format=collections.defaultdict(set)
    for r in rows:by_format[r['format']].add(r['group'])
    if any(len(v)<4 for v in by_format.values()):raise ValueError('Need at least four independent states per format for held-out evaluation')
    # Group assignment is independent of labels. All policies/collection rounds
    # for a starting state stay together, including the final coefficient holdout.
    held={group for v in by_format.values() for group in sorted(v)[-math.ceil(len(v)/4):]}
    dev=[r for r in rows if r['group'] not in held];test=[r for r in rows if r['group'] in held]
    folds={group:i%3 for fmt,groups in sorted(by_format.items()) for i,group in enumerate(sorted(groups-held))}
    reports=[]
    for fold in range(3):
        train=[r for r in dev if folds[r['group']]!=fold];valid=[r for r in dev if folds[r['group']]==fold]
        if train and valid:reports.append(metrics(valid,fit_heads(train)))
    model=fit_heads(dev)
    model['provenance']=dict(manifests=[dict(name=Path(p).name,sha256=sha(p)) for p in args.manifest],
                             development_states=sorted({r['group'] for r in dev}),heldout_states=sorted(held),
                             cross_validation=reports,holdout=metrics(test,model),
                             weighting='equal format, then state, then collection, then episode',
                             regularization=dict(logistic_C=1,ridge_alpha=100),
                             note='Holdout is excluded from coefficients; validation does not replace prospective gameplay measurements.')
    save(args.output,model)
    print(json.dumps(model['provenance'],indent=2))
    if args.header:emit(model,args.header)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    sub=parser.add_subparsers(dest='command',required=True)
    p=sub.add_parser('run');p.add_argument('--binary',required=True);p.add_argument('--output',required=True)
    p.add_argument('--plan');p.add_argument('--seeds',type=int,nargs='+',default=[5101,5102,5103,5104])
    p.add_argument('--ticks',type=int,default=90000);p.add_argument('--threads',type=int,default=4);p.add_argument('--jobs',type=int,default=1);p.set_defaults(action=run)
    p=sub.add_parser('fit');p.add_argument('--manifest',action='append',required=True);p.add_argument('--output',required=True);p.add_argument('--header');p.set_defaults(action=fit)
    p=sub.add_parser('emit');p.add_argument('--model',default=str(DEFAULT_MODEL));p.add_argument('--header',default=str(HEADER));p.set_defaults(action=lambda a:emit(json.loads(Path(a.model).read_text()),a.header))
    args=parser.parse_args()
    if args.command=='run' and min(args.jobs,args.threads,args.ticks)<1:parser.error('jobs, threads and ticks must be positive')
    args.action(args)

if __name__=='__main__':main()
