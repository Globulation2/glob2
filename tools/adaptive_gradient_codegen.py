"""Generate one integer evaluator and an explicit family-to-heads dispatch."""
from pathlib import Path
from tools import adaptive_gradient_dataset as f


def _heads(name, model):
    """Only coefficient data repeats; all families use the same arithmetic."""
    from tools.resource_gradient_model import HEADS
    values = []
    for key in HEADS:
        head = model[key]
        coefficients = ','.join(map(str, head['coef']))
        values.append('{{' + coefficients + '},' + str(head['bias']) + 'LL,' + str(head['shift']) + '}')
    return f'inline constexpr Heads {name}={{' + ','.join(values) + '};\n'


def render(model):
    from tools import resource_gradient_model as math
    from tools.adaptive_gradient_model import DEPLOYMENT_AGE_CAP_TICKS, validate
    validate(model)
    dimension = len(model['features'])
    experts = model.get('family_experts', {})
    text = '''// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by tools/adaptive_gradient_model.py; do not edit coefficients here.
// Model replacement changes simulation behavior and requires a SIM_REVISION bump.
#pragma once
#include <algorithm>
#include <array>
#include <bit>
#include <cstdint>
#include <limits>
namespace AdaptiveGradientModel {
using I=std::int64_t;
// Capture/collector state keeps its original shape independently of dispatch.
inline constexpr unsigned BaseFeatureCount=7;
using BaseFeatures=std::array<I,BaseFeatureCount>;
'''
    text += f'inline constexpr char ContractId[]="{f.CONTRACT_ID}";\n'
    text += f'inline constexpr bool Trained={str(model["trained"]).lower()};\n'
    text += f'inline constexpr I ThresholdMilli={model["threshold"]};\n'
    age_cap = model.get('deployment', {}).get('demanded_age_cap_ticks', DEPLOYMENT_AGE_CAP_TICKS)
    text += '// Current engine deployment cap; historical fit metrics remain unchanged.\n'
    text += f'inline constexpr unsigned DemandedAgeCapTicks={age_cap};\n'
    text += f'inline constexpr unsigned CounterCount={len(f.COUNTER_IDS)};\n'
    text += 'inline constexpr std::array<unsigned,CounterCount> RequiredMovementCounters={' + ','.join(map(str, f.COUNTER_IDS)) + '};\n'
    text += f'inline constexpr unsigned RequiredMovementMask={sum(1 << i for i in f.COUNTER_IDS)};\n'
    text += 'using MovementCounts=std::array<std::uint64_t,CounterCount>;\n'
    text += f'inline constexpr unsigned SelectedFeatureCount={dimension};\n'
    text += 'using SelectedFeatures=std::array<I,SelectedFeatureCount>;\n'
    text += f'inline constexpr unsigned FamilyExpertCount={len(experts)};\n'
    text += 'inline constexpr unsigned UnknownFamily=std::numeric_limits<unsigned>::max();\n'
    text += 'inline I clamp(I x) { return std::clamp(x,I(0),I(1000000)); }\n'
    text += 'inline constexpr I LogLut[]={' + ','.join(map(str, math.LOG)) + '};\n'
    text += 'inline constexpr I SigLut[]={' + ','.join(map(str, math.SIG)) + '};\n'
    text += '''// Q12 log2(1+x) and Q16 sigmoid interpolate with integers only.
// Signed division truncates toward zero, including negative linear heads.
inline I log(I x) {
    const I n=clamp(x)+1,b=std::bit_width(std::uint64_t(n))-1,base=I(1)<<b;
    const I pos=((n-base)<<16)/base,i=pos>>8,f=pos&255;
    return (b<<12)+LogLut[i]+(LogLut[i+1]-LogLut[i])*f/256;
}
inline I clip(I x) { return std::clamp(x,I(-1000000000),I(1000000000)); }
inline I sigmoid(I z) {
    z=std::clamp(z,I(-12000),I(12000));const I n=z+12000,i=std::min(n/50,I(479)),r=n-i*50;
    return SigLut[i]+(SigLut[i+1]-SigLut[i])*r/50;
}
'''
    if dimension > len(f.BASE_FEATURES):
        text += '''// Rates use uncapped counters. The overflow path is portable binary division.
inline I fraction(std::uint64_t events,std::uint64_t queries) {
    if (!queries) return 0;
    if (events>=queries) return 4096;
    if (events<=std::numeric_limits<std::uint64_t>::max()/4096)
        return I(events*4096/queries);
    I result=0;
    for (unsigned bit=0;bit<12;++bit) {
        result<<=1;
        if (events>=queries-events) { events-=queries-events; result|=1; }
        else events+=events;
    }
    return result;
}
'''
    text += 'inline SelectedFeatures prepare(const BaseFeatures& base,const MovementCounts& counts) {\n'
    expressions = [f'base[{i}]' for i in range(len(f.BASE_FEATURES))]
    if dimension == len(f.BASE_FEATURES):
        text += '    (void)counts; // Historical seven-input model; capture ABI remains unchanged.\n'
    else:
        text += '    const auto bounded=[](std::uint64_t value) { return I(std::min<std::uint64_t>(value,1000000)); };\n'
        expressions += [f'bounded(counts[{i}])' for i in range(len(f.COUNTERS))]
        expressions += [f'fraction(counts[{i}],counts[{len(f.COUNTERS)-1}])' for i in range(len(f.FRACTIONS))]
    text += '    return {' + ','.join(expressions) + '};\n}\n'
    text += '''struct LinearHead { SelectedFeatures coefficients; I bias; unsigned shift; };
struct Heads { LinearHead positiveProbability,negativeProbability,positiveMean,negativeMean; };
'''
    text += _heads('Combined', model)
    for identifier, expert in sorted(experts.items(), key=lambda item: int(item[0])):
        text += _heads('Family' + identifier, expert)
    text += '''// Combined was fitted on all measured families. An absent, unmeasured or
// future family uses it explicitly; no caller-supplied ID indexes an array.
inline const Heads& selectHeads(unsigned family) {
'''
    if experts:
        text += '    switch (family) {\n'
        for identifier in sorted(experts, key=int):
            text += f'    case {identifier}: return Family{identifier};\n'
        text += '    default: return Combined;\n    }\n'
    else:
        text += '    (void)family; return Combined;\n'
    text += '''}
inline I linear(const SelectedFeatures& x,const LinearHead& head) {
    I z=head.bias;
    for (unsigned i=0;i<SelectedFeatureCount;++i) z+=x[i]*head.coefficients[i];
    return clip(z/(I(1)<<head.shift));
}
inline int predict(const BaseFeatures& base,const MovementCounts& counts,unsigned family=UnknownFamily) {
    auto x=prepare(base,counts);
'''
    for index, transform in enumerate(model['transforms']):
        if transform == 'log1p_q12':
            text += f'    x[{index}]=log(x[{index}]);\n'
    text += '''    const auto& heads=selectHeads(family);
    const I pp=sigmoid(linear(x,heads.positiveProbability)),pn=sigmoid(linear(x,heads.negativeProbability));
    const I mp=std::max(I(0),linear(x,heads.positiveMean)),mn=std::max(I(0),linear(x,heads.negativeMean));
    return int(clip((pp*mp-pn*mn)/65536));
}
} // namespace AdaptiveGradientModel
'''
    return text


def emit(model, path):
    Path(path).write_text(render(model))
