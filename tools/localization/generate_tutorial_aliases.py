#!/usr/bin/env python3
"""Generate display-only aliases for tutorial text embedded in maps and old saves.

This never edits scripts or maps: their instructions, state and byte offsets stay
intact. Exact aliases let the client display the current translated tutorial.
"""
import argparse
import gzip
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = Path('src/ui/TutorialTextAliases.h')
SHOW = re.compile(r'\s*show\("(.*)"\s*(?:,\s*([a-z-]+))?\s*\)\s*$')
TITLES = {
    'Tutorial Campaign': '[tutorial]',
    'Introduction and Basics': '[tutorial mission basics]',
    'More building and Schools': '[tutorial mission development]',
    'Warriors, Training Camps, and Upgrades': '[tutorial mission training]',
    'Flags and Completion': '[tutorial mission flags]',
}


def messages(text, part):
    number = 0
    key = None
    for line in text.splitlines():
        match = SHOW.fullmatch(line)
        if not match:
            continue
        value, language = match.groups()
        if language is None:
            number += 1
            key = f'[tutorial part{part} message {number}]'
        if key is None:
            raise ValueError('Tutorial translation precedes its English source')
        yield key, value



def embedded_source(path):
    raw = gzip.decompress(path.read_bytes())
    start = raw.find(b"# glob2's tutorial")
    if start < 4:
        raise ValueError(f'{path}: tutorial source not found')
    length = int.from_bytes(raw[start - 4:start], 'big')
    if not length or start + length > len(raw):
        raise ValueError(f'{path}: invalid embedded source length')
    return raw[start:start + length]


def sources(root=ROOT):
    for part in range(1, 5):
        yield part, (root / f'scripts/tutorial_part{part}.sgsl').read_bytes()
        yield part, embedded_source(root / f'campaigns/tutorial-part{part}.map.gz')


def fingerprint(source):
    # Windows checkouts/old saves may use CRLF; line endings do not change
    # tutorial identity. Do not normalize or rewrite the serialized script.
    source = source.replace(b'\r\n', b'\n')
    value = 14695981039346656037
    for byte in source:
        value = ((value ^ byte) * 1099511628211) & ((1 << 64) - 1)
    return value, len(source)

def aliases(root=ROOT):
    found = dict(TITLES)
    for part, source in sources(root):
        for key, value in messages(source.decode('utf-8'), part):
            previous = found.setdefault(value, key)
            if previous != key:
                # The legacy Spanish pool instructions repeat the same text
                # twice. Both current messages intentionally share wording.
                if {previous, key} != {'[tutorial part2 message 29]', '[tutorial part2 message 30]'}:
                    raise ValueError(f'Ambiguous tutorial alias: {previous} / {key}')
    return found


def render(root=ROOT):
    entries = aliases(root)
    lines = [
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        '// Generated by tools/localization/generate_tutorial_aliases.py; do not edit.',
        '#pragma once', '#include <string_view>', '#include <utility>', '#include <cstdint>', '#include <cstddef>',
        'namespace Glob2UI', '{',
        'inline constexpr std::pair<std::string_view, std::string_view> tutorialTextAliases[] = {',
    ]
    for value, key in sorted(entries.items()):
        lines.append('\t{' + json.dumps(value, ensure_ascii=False) + ', ' + json.dumps(key) + '},')
    lines.append('};')
    lines.append('inline constexpr std::pair<std::uint64_t, std::size_t> tutorialSourceSignatures[] = {')
    for digest, size in sorted({fingerprint(source) for _, source in sources(root)}):
        lines.append(f'\t{{{digest}ull, {size}}},')
    lines.extend(['};', '} // namespace Glob2UI', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify generated aliases without writing')
    args = parser.parse_args()
    output = ROOT / OUTPUT
    expected = render()
    if args.check:
        if not output.exists() or output.read_text(encoding='utf-8') != expected:
            parser.exit(1, 'Tutorial aliases are stale; run tools/localization/generate_tutorial_aliases.py\n')
    else:
        output.write_text(expected, encoding='utf-8')
    print(f'{len(aliases())} tutorial display aliases verified')


if __name__ == '__main__':
    main()
