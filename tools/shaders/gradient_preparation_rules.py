#!/usr/bin/env python3
"""Generate restricted, pure unsigned integer gradient preparation predicates.

The source admits parameters, uint32 literals, boolean/bit operations and select.
It cannot execute code, access memory, loop, or invoke arbitrary functions.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'src/field/shaders/preparation-rules.json'
# Restrict the shared dialect to portable ASCII identifiers. Shader/C++ reserved
# words and implementation namespaces cannot be emitted as user parameters.
RESERVED = set("""alignas alignof and and_eq asm atomic auto bitand bitor bool break
case catch char class compl const consteval constexpr constinit continue default
 delete discard do double else enum explicit export extern false float for friend
 goto half if inline in inout int invariant layout long mutable namespace new noinline
 not not_eq operator or or_eq out override packed precise private protected public
 register reinterpret_cast restrict return sampler shared short signed sizeof static
 struct switch template this thread_local throw true try typedef typename uint union
 unsigned using varying virtual void volatile while xor xor_eq buffer uniform
 precision lowp mediump highp subroutine coherent readonly writeonly gl
 char8_t char16_t char32_t wchar_t concept requires const_cast dynamic_cast
 static_cast static_assert decltype thread_local noexcept nullptr co_await co_return
 co_yield typename typeid final override vec2 vec3 vec4 ivec2 ivec3 ivec4 uvec2
 uvec3 uvec4 bvec2 bvec3 bvec4 dvec2 dvec3 dvec4 mat2 mat3 mat4""".split())


def identifier(value):
    return (isinstance(value, str) and re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*', value)
            and '__' not in value and not value.startswith('gl_') and value not in RESERVED)


def validate(source):
    if not isinstance(source, dict) or set(source) != {'version', 'functions'}:
        raise ValueError('Invalid rule source schema')
    if type(source['version']) is not int or source['version'] != 1:
        raise ValueError('Unsupported rule source version')
    if not isinstance(source['functions'], list) or not source['functions']:
        raise ValueError('Expected nonempty function list')
    names = set()
    for function in source['functions']:
        if not isinstance(function, dict) or set(function) != {'name', 'parameters', 'expression'}:
            raise ValueError('Invalid rule function schema')
        name, parameters = function['name'], function['parameters']
        if not identifier(name) or name in names:
            raise ValueError('Invalid or duplicate function name')
        if not isinstance(parameters, list) or any(not identifier(p) for p in parameters):
            raise ValueError('Invalid parameter name')
        if len(set(parameters)) != len(parameters) or name in parameters:
            raise ValueError('Duplicate or shadowing parameter name')
        names.add(name)
        expression(function['expression'], parameters)


def expression(node, parameters):
    if isinstance(node, str):
        if node not in parameters:
            raise ValueError('Unknown parameter: ' + node)
        return node
    if type(node) is int:
        if not 0 <= node <= 0xffffffff:
            raise ValueError('Literal outside uint32')
        return str(node) + 'u'
    if not isinstance(node, list) or not node:
        raise ValueError('Invalid expression')
    op, *args = node
    arity = {'select': 3, 'or': 2, 'and': 2, 'not': 1, 'bitOr': 2, 'shift': 2}
    if not isinstance(op, str) or op not in arity or len(args) != arity[op]:
        raise ValueError('Invalid operator or arity')
    if op == 'shift' and (type(args[1]) is not int or not 0 <= args[1] < 32):
        raise ValueError('Shift must have a constant uint32 width')
    rendered = [expression(arg, parameters) for arg in args]
    if op == 'select':
        return '(' + rendered[0] + ' != 0u ? ' + rendered[1] + ' : ' + rendered[2] + ')'
    if op == 'not':
        return '(' + rendered[0] + ' == 0u ? 1u : 0u)'
    if op in ('or', 'and'):
        symbol = '||' if op == 'or' else '&&'
        return '((' + rendered[0] + ' != 0u ' + symbol + ' ' + rendered[1] + ' != 0u) ? 1u : 0u)'
    return '(' + rendered[0] + (' | ' if op == 'bitOr' else ' << ') + rendered[1] + ')'


def outputs(source):
    validate(source)
    result = {}
    for target, scalar in [('h', 'std::uint32_t'), ('cl', 'uint'), ('glsl', 'uint')]:
        lines = ['// SPDX-License-Identifier: GPL-3.0-or-later',
                 '// Generated by tools/shaders/gradient_preparation_rules.py; do not edit.']
        if target == 'h':
            lines += ['#pragma once', '#include <cstdint>', 'namespace gradient_preparation::rules {']
        for function in source['functions']:
            name, parameters = function['name'], function['parameters']
            signature = ', '.join(scalar + ' ' + p for p in parameters)
            prefix = 'inline constexpr ' if target == 'h' else ''
            lines += [prefix + scalar + ' ' + name + '(' + signature + ') {',
                      '    return ' + expression(function['expression'], parameters) + ';', '}']
        if target == 'h':
            lines.append('}')
        path = ROOT / ('src/field/GradientPreparationRules.h' if target == 'h'
                       else 'src/field/shaders/preparation-rules.' + target)
        result[path] = '\n'.join(lines) + '\n'
    return result


def verify():
    for path, content in outputs(json.loads(SOURCE.read_text())).items():
        if not path.exists() or path.read_text() != content:
            raise ValueError('Stale preparation rules: ' + str(path.relative_to(ROOT)))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--generate', action='store_true')
    args = parser.parse_args()
    if args.generate:
        for path, content in outputs(json.loads(SOURCE.read_text())).items():
            path.write_text(content)
    else:
        verify()
