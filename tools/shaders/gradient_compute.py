#!/usr/bin/env python3
"""Rebuild and verify the embedded gradient compute bundle using pinned tools."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[2]
DIRECTORY = ROOT / 'src/field/shaders'
HEADER = ROOT / 'src/field/GradientComputeShaders.h'
BUNDLE_FILES = frozenset({
    'src/field/GradientComputeShaders.h', 'tools/shaders/gradient_compute.py',
    *(f'src/field/shaders/{name}{suffix}'
      for name in ('frozen8', 'jacobi', 'validate') for suffix in ('.comp', '.wgsl')),
})
VULKAN_FILES = frozenset({'vk_platform.h', 'vulkan_core.h', 'LICENSE.txt'})


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def normalized_translation(source):
    # Naga emits whitespace after some attributes. Keep generated, embedded and
    # hashed text identical without carrying trailing whitespace into commits.
    return '\n'.join(line.rstrip() for line in source.splitlines()) + '\n'


def verify(root=ROOT):
    directory = root / 'src/field/shaders'
    manifest = json.loads((directory / 'manifest.json').read_text())
    # An omitted receipt must fail too: checking only listed files would let an
    # incomplete manifest silently disconnect generated code from its source.
    if manifest.get('version') != 1 or manifest.get('target') != 'vulkan1.0':
        raise ValueError('Unsupported gradient shader manifest contract')
    if set(manifest.get('files', {})) != BUNDLE_FILES:
        raise ValueError('Incomplete or unexpected gradient shader file receipts')
    for relative, expected in manifest['files'].items():
        if digest(root / relative) != expected:
            raise ValueError('Stale gradient shader bundle: ' + relative + '; regenerate with tools/shaders/gradient_compute.py')
    if manifest['glslang'] != '15.1.0' or manifest['naga'] != '27.0.0':
        raise ValueError('Unexpected gradient shader compiler version')
    header_root = root / 'third_party/vulkan'
    headers = json.loads((header_root / 'manifest.json').read_text())
    if headers.get('version') != '1.2.162' or set(headers.get('files', {})) != VULKAN_FILES:
        raise ValueError('Unexpected pinned Vulkan header contract')
    for name, expected in headers['files'].items():
        if digest(header_root / name) != expected:
            raise ValueError('Vulkan header differs from its pinned source: ' + name)
    return manifest


def generate(compiler, naga, output):
    version = subprocess.check_output([compiler, '--version'], text=True)
    if not re.search(r'^Glslang Version: \d+:15\.1\.0$', version, re.M):
        raise ValueError('Gradient shaders require glslang 15.1.0')
    if subprocess.check_output([naga, '--version'], text=True).strip() != '27.0.0':
        raise ValueError('Gradient shaders require Naga 27.0.0')
    output.mkdir(parents=True, exist_ok=True)
    artifact_hashes = []
    header = ['// SPDX-License-Identifier: GPL-3.0-or-later', '// Generated by tools/shaders/gradient_compute.py; do not edit.', '#pragma once', '#include <cstdint>', 'namespace gradient_shaders {']
    for name in ('frozen8', 'jacobi', 'validate'):
        binary = output / (name + '.spv')
        subprocess.run([compiler, '-V', '--target-env', 'vulkan1.0', str(DIRECTORY / (name + '.comp')), '-o', str(binary)], check=True)
        wgsl = DIRECTORY / (name + '.wgsl')
        subprocess.run([naga, str(binary), str(wgsl)], check=True)
        wgsl.write_text(normalized_translation(wgsl.read_text()))
        artifact_hashes.extend([digest(binary), digest(wgsl)])
        words = struct.unpack('<' + 'I' * (binary.stat().st_size // 4), binary.read_bytes())
        header.append('inline constexpr std::uint32_t ' + name + '[] = {')
        header.extend(','.join('0x%08x' % word for word in words[i:i+8]) + ',' for i in range(0, len(words), 8))
        header.append('};')
        header.append('inline constexpr char ' + name + 'WGSL[] = R"WGSL(' + wgsl.read_text() + ')WGSL";')
    identity = hashlib.sha256(''.join(artifact_hashes).encode()).hexdigest()
    header.append('inline constexpr char identity[] = "' + identity + '";')
    header.append('}')
    HEADER.write_text('\n'.join(header) + '\n')
    files = [HEADER, ROOT / 'tools/shaders/gradient_compute.py']
    files.extend(DIRECTORY / (name + suffix) for name in ('frozen8', 'jacobi', 'validate') for suffix in ('.comp', '.wgsl'))
    manifest = {'version': 1, 'glslang': '15.1.0', 'naga': '27.0.0', 'target': 'vulkan1.0',
                'files': {str(path.relative_to(ROOT)): digest(path) for path in files}}
    (DIRECTORY / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--glslang')
    parser.add_argument('--naga')
    parser.add_argument('--output', type=Path, default=ROOT / 'artifacts/gradient-shaders')
    args = parser.parse_args()
    if bool(args.glslang) != bool(args.naga):
        parser.error('--glslang and --naga must be supplied together')
    if args.glslang and args.naga:
        generate(args.glslang, args.naga, args.output)
    else:
        verify()
